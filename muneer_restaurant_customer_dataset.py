"""## Customer Segmentation (K-Means)

### Subtask:
Perform customer segmentation using the K-Means clustering algorithm based on relevant customer behavior features (e.g., recency, frequency, monetary value). Create distinct customer segments such as VIP, Loyal, At-Risk, New, and Low Value Customers. Provide targeted marketing recommendations for each identified segment.

**Reasoning**:
I need to prepare the data for K-Means clustering by selecting and scaling relevant features. This involves first calculating the mean 'last_order_days' per customer and merging it with the existing customer_summary. Then, I will select the features ('total_orders_per_customer', 'mean_last_order_days', 'total_profit_per_customer') and apply StandardScaler.
"""

from sklearn.preprocessing import StandardScaler

# Calculate mean last_order_days per customer
mean_last_order_days_per_customer = df.groupby('customer_id')['last_order_days'].mean().reset_index()
mean_last_order_days_per_customer.rename(columns={'last_order_days': 'mean_last_order_days'}, inplace=True)

# Merge with customer_summary
customer_summary = pd.merge(customer_summary, mean_last_order_days_per_customer, on='customer_id', how='left')

# Select relevant features for clustering: Recency (mean_last_order_days), Frequency (total_orders_per_customer), Monetary (total_profit_per_customer)
features_for_clustering = ['mean_last_order_days', 'total_orders_per_customer', 'total_profit_per_customer']
customer_features = customer_summary[features_for_clustering]

# Scale the features
scaler = StandardScaler()
customer_features_scaled = scaler.fit_transform(customer_features)
customer_features_scaled = pd.DataFrame(customer_features_scaled, columns=features_for_clustering, index=customer_summary.index)

print("Customer Summary with Mean Last Order Days:")
print(customer_summary.head())
print("\nScaled Customer Features for Clustering (first 5 rows):")
print(customer_features_scaled.head())

"""**Reasoning**:
The next step is to determine the optimal number of clusters using the Elbow Method. This involves running K-Means for a range of cluster numbers and plotting the inertia to find the 'elbow' point.


"""

from sklearn.cluster import KMeans
import matplotlib.pyplot as plt

# Determine the optimal number of clusters using the Elbow Method
wcss = [] # Within-cluster sum of squares
for i in range(1, 11):
    kmeans = KMeans(n_clusters=i, init='k-means++', random_state=42, n_init=10)
    kmeans.fit(customer_features_scaled)
    wcss.append(kmeans.inertia_)

# Plot the Elbow Method graph
plt.figure(figsize=(10, 6))
plt.plot(range(1, 11), wcss, marker='o', linestyle='--')
plt.title('Elbow Method to Determine Optimal K')
plt.xlabel('Number of Clusters (K)')
plt.ylabel('Within-Cluster Sum of Squares (WCSS)')
plt.xticks(range(1, 11))
plt.grid(True)
plt.show()

"""**Reasoning**:
The Elbow Method plot has been generated, and now I need to apply K-Means clustering with an optimal number of clusters (K). I'll choose K=4 based on the plot and assign the cluster labels to the customer summary.


"""

n_clusters = 4 # Choosing 4 based on the elbow plot visual inspection
kmeans = KMeans(n_clusters=n_clusters, init='k-means++', random_state=42, n_init=10)
customer_summary['cluster_label'] = kmeans.fit_predict(customer_features_scaled)

print(f"K-Means clustering applied with {n_clusters} clusters.")
print("\nCustomer Summary with Cluster Labels (first 5 rows):")
print(customer_summary.head())

print("\nDistribution of Customer Segments by Cluster:")
print(customer_summary['cluster_label'].value_counts().sort_index())

